    private static int[] keySchedule(final int[] data16) {
        final int[] out = new int[272];
        System.arraycopy(data16, 0, out, 0, 16);
        final int[] buf = new int[17];
        System.arraycopy(data16, 0, buf, 0, 16);
        int checksum = 0;
        for (int i = 0; i < 16; i++) checksum ^= data16[i];
        buf[16] = checksum & 0xff;
        for (int rnd = 0; rnd < 16; rnd++) {
            for (int i = 0; i < 17; i++) {
                final int b = buf[i];
                buf[i] = ((b << 3) | (b >>> 5)) & 0xff;
            }
            int readPos = (rnd + 1) % 17;
            for (int j = 0; j < 16; j++) {
                final int src = buf[readPos];
                final int tblIdx = 0xf + rnd * 16 - j;
                out[16 + rnd * 16 + j] = (KS_TABLE[tblIdx] + src) & 0xff;
                readPos++;
                if (readPos > 16) readPos = 0;
            }
        }
        return out;
    }

    private static int[] fibonacciMix(final int[] s) {
        final int[] r = new int[29];
        r[16]=s[0]; r[17]=s[1]; r[3]=s[2]; r[4]=s[3];
        r[5]=s[4]; r[6]=s[5]; r[7]=s[6]; r[19]=s[7];
        r[20]=s[8]; r[21]=s[9]; r[22]=s[10]; r[23]=s[11];
        r[24]=s[12]; r[25]=s[13]; r[26]=s[14]; r[27]=s[15];

        // Stage 1
        r[28]=r[17]+r[16]*2; r[16]=r[17]+r[16];
        r[17]=r[4]+r[3]*2;   r[3]=r[4]+r[3];
        r[4]=r[6]+r[5]*2;    r[5]=r[6]+r[5];
        r[6]=r[19]+r[7]*2;   r[7]=r[19]+r[7];
        r[19]=r[21]+r[20]*2; r[20]=r[21]+r[20];
        r[21]=r[23]+r[22]*2; r[22]=r[23]+r[22];
        r[23]=r[25]+r[24]*2; r[24]=r[25]+r[24];
        r[25]=r[27]+r[26]*2; r[26]=r[27]+r[26];

        // Stage 2
        r[27]=r[22]+r[19]*2; r[19]=r[22]+r[19];
        r[22]=r[26]+r[23]*2; r[23]=r[26]+r[23];
        r[26]=r[16]+r[17]*2; r[16]=r[17]+r[16];
        r[17]=r[5]+r[6]*2;   r[5]=r[6]+r[5];
        r[6]=r[20]+r[21]*2;  r[20]=r[21]+r[20];
        r[21]=r[24]+r[25]*2; r[24]=r[25]+r[24];
        r[25]=r[7]+r[28]*2;  r[7]=r[7]+r[28];
        r[28]=r[3]+r[4]*2;   r[3]=r[4]+r[3];

        // Stage 3
        r[4]=r[24]+r[6]*2;   r[6]=r[24]+r[6];
        r[24]=r[3]+r[25]*2;  r[3]=r[25]+r[3];
        r[25]=r[19]+r[22]*2; r[19]=r[22]+r[19];
        r[22]=r[16]+r[17]*2; r[16]=r[17]+r[16];
        r[17]=r[20]+r[21]*2; r[20]=r[21]+r[20];
        r[21]=r[7]+r[28]*2;  r[7]=r[7]+r[28];
        r[28]=r[5]+r[27]*2;  r[5]=r[27]+r[5];
        r[27]=r[23]+r[26]*2; r[23]=r[23]+r[26];

        // Stage 4
        r[26]=r[7]+r[17]*2;  r[17]=r[17]+r[7];
        r[7]=r[23]+r[28]*2;  r[23]=r[23]+r[28];
        r[28]=r[6]+r[24]*2;  r[6]=r[6]+r[24];
        r[24]=r[19]+r[22]*2; r[19]=r[19]+r[22];
        r[22]=r[20]+r[21]*2; r[20]=r[20]+r[21];
        r[21]=r[5]+r[27]*2;  r[5]=r[27]+r[5];
        r[27]=r[16]+r[4]*2;  r[16]=r[4]+r[16];
        r[4]=r[3]+r[25]*2;   r[3]=r[25]+r[3];

        return new int[]{
                r[26]&0xff, r[17]&0xff, r[7]&0xff, r[23]&0xff,
                r[28]&0xff, r[6]&0xff, r[24]&0xff, r[19]&0xff,
                r[22]&0xff, r[20]&0xff, r[21]&0xff, r[5]&0xff,
                r[27]&0xff, r[16]&0xff, r[4]&0xff, r[3]&0xff,
        };
    }

    private static final int MASK = 0x9999;

    private static int[] condMix(final int[] state, final int[] keyBlock, final int keyOff, final int phase) {
        final int[] result = state.clone();
        for (int i = 0; i < 16; i++) {
            final boolean bitSet = ((1 << i) & MASK) != 0;
            if (phase == 3) {
                result[i] = bitSet ? (result[i] ^ keyBlock[keyOff + i])
                                   : ((keyBlock[keyOff + i] + result[i]) & 0xff);
            } else {
                result[i] = bitSet ? ((keyBlock[keyOff + i] + result[i]) & 0xff)
                                   : (result[i] ^ keyBlock[keyOff + i]);
            }
        }
        return result;
    }

    private static int[] sboxSub(final int[] state) {
        final int[] result = state.clone();
        final int[] sIdx = {0,3,4,7,8,11,12,15};
        final int[] iIdx = {1,2,5,6,9,10,13,14};
        for (int pos : sIdx) result[pos] = SBOX[result[pos] & 0xff];
        for (int pos : iIdx) result[pos] = ISBOX[result[pos] & 0xff];
        return result;
    }

    private static int[] blockCipher(final int[] stateIn, final int[] ek, final int mode) {
        int[] s = stateIn.clone();
        final int[] initial = stateIn.clone();
        s = condMix(s, ek, 0, 3);
        s = sboxSub(s);
        s = condMix(s, ek, 16, 5);
        for (int x9 = 1; x9 <= 8; x9++) {
            s = fibonacciMix(s);
            final int ekOff = x9 * 0x20;
            if (x9 == 8) {
                s = condMix(s, ek, 0x100, 3);
                break;
            }
            if (mode != 0 && x9 == 2) {
                for (int i = 0; i < 16; i++) {
                    final boolean bitSet = ((1 << i) & MASK) != 0;
                    s[i] = bitSet ? (s[i] ^ initial[i]) : ((initial[i] + s[i]) & 0xff);
                }
            }
            s = condMix(s, ek, ekOff, 3);
            s = sboxSub(s);
            s = condMix(s, ek, ekOff + 16, 5);
        }
        return s;
    }

    static int[] functionE1test(final byte[] key6, final int[] input16, final byte[] seed16) {
        final int[] expandedKey = new int[16];
        for (int i = 0; i < 16; i++) expandedKey[i] = key6[i % 6] & 0xff;
        final int[] output = input16.clone();
        final int[] seed = new int[16];
        for (int i = 0; i < 16; i++) seed[i] = seed16[i] & 0xff;
        final int[] ks1 = keySchedule(seed);
        int[] cipherOut = blockCipher(output, ks1, 0);
        for (int i = 0; i < 16; i++) {
            cipherOut[i] = (expandedKey[i] + (cipherOut[i] ^ input16[i])) & 0xff;
        }
        final int[] obf = new int[]{
                (seed[0]  - 0x17) & 0xff,  (seed[1]  ^ 0xe5) & 0xff,
                (seed[2]  - 0x21) & 0xff,  (seed[3]  ^ 0xc1) & 0xff,
                (seed[4]  - 0x4d) & 0xff,  (seed[5]  ^ 0xa7) & 0xff,
                (seed[6]  - 0x6b) & 0xff,  (seed[7]  ^ 0x83) & 0xff,
                (seed[8]  ^ 0xe9) & 0xff,  (seed[9]  - 0x1b) & 0xff,
                (seed[10] ^ 0xdf) & 0xff,  (seed[11] - 0x3f) & 0xff,
                (seed[12] ^ 0xb3) & 0xff,  (seed[13] - 0x59) & 0xff,
                (seed[14] ^ 0x95) & 0xff,  (seed[15] - 0x7d) & 0xff,
        };
        final int[] ks2 = keySchedule(obf);
        return blockCipher(cipherOut, ks2, 1);
    }

    /** Build a [0x00, rand*16] auth init packet. */
    public static byte[] getRandomAuthData() {
        final byte[] result = new byte[17];
        result[0] = 0x00;
        final byte[] rnd = new byte[16];
        RANDOM.nextBytes(rnd);
        System.arraycopy(rnd, 0, result, 1, 16);
        return result;
    }

    /** Encrypt a device challenge [0x00, challenge*16] -> [0x01, encrypted*16]. */
    public static byte[] getEncryptedAuthData(final byte[] deviceData17) {
        if (deviceData17 == null || deviceData17.length != 17) {
            throw new IllegalArgumentException("device data must be 17 bytes");
        }
        final int[] input16 = new int[16];
        for (int i = 0; i < 16; i++) input16[i] = deviceData17[i + 1] & 0xff;
        final int[] encrypted = functionE1test(MAGIC, input16, STATIC_KEY);
        final byte[] result = new byte[17];
        result[0] = 0x01;
        for (int i = 0; i < 16; i++) result[i + 1] = (byte) encrypted[i];
        return result;
    }
